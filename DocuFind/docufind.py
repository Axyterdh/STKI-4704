import pandas as pd
from sklearn.metrics.pairwise import cosine_similarity

# Daftar query pengujian
queries = {
    "Q1": "belajar pemrograman python",
    "Q2": "belajar database dan SQL",
    "Q3": "jaringan komputer dan protokol",
    "Q4": "kecerdasan buatan",
    "Q5": "membuat dan mengembangkan website"
}

# Ground truth: dokumen yang dianggap relevan
ground_truth = {
    "Q1": {"D01", "D02", "D03", "D04"},
    "Q2": {"D05", "D06", "D07", "D08"},
    "Q3": {"D09", "D10", "D11", "D12"},
    "Q4": {"D13", "D14", "D15", "D16"},
    "Q5": {"D17", "D18", "D19", "D20"}
}

# Jumlah hasil pencarian
top_k = 5

hasil_evaluasi = []

for kode_query, query in queries.items():

    # Preprocessing query
    query_bersih = preprocessing(query)

    # Mengubah query menjadi vektor TF-IDF
    query_vector = tfidf_vectorizer.transform([query_bersih])

    # Menghitung Cosine Similarity
    skor = cosine_similarity(
        query_vector,
        tfidf_matrix
    ).flatten()

    # Mengambil 5 dokumen dengan skor tertinggi
    indeks_teratas = skor.argsort()[::-1][:top_k]

    # Mengambil ID dokumen hasil pencarian
    dokumen_ditemukan = [
        df.iloc[i]["id_dokumen"]
        for i in indeks_teratas
    ]

    # Menghitung jumlah dokumen relevan yang ditemukan
    relevan_ditemukan = len(
        set(dokumen_ditemukan) & ground_truth[kode_query]
    )

    # Menghitung Precision dan Recall
    precision = relevan_ditemukan / top_k

    recall = (
        relevan_ditemukan / len(ground_truth[kode_query])
    )

    # Menghitung F1-Score
    if precision + recall > 0:
        f1_score = (
            2 * precision * recall / (precision + recall)
        )
    else:
        f1_score = 0

    hasil_evaluasi.append({
        "Query": kode_query,
        "Kata Kunci": query,
        "Dokumen Ditemukan": ", ".join(dokumen_ditemukan),
        "Relevan Ditemukan": relevan_ditemukan,
        "Precision": precision,
        "Recall": recall,
        "F1-Score": f1_score
    })

# Menampilkan hasil evaluasi
df_evaluasi = pd.DataFrame(hasil_evaluasi)

display(df_evaluasi.round(3))

# Menghitung rata-rata setiap metrik
